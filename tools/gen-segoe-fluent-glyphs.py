#!/usr/bin/env python3
"""Regenerate windows/src/inc/AxanSegoeFluentGlyphs.h, the icon picker's name table (#39).

Source: upstream Windows Terminal's
    windows/src/cascadia/TerminalSettingsEditor/SegoeFluentIconList.h
which is itself adapted from Microsoft's WinUI Gallery glyph list
(WinUIGallery/DataModel/IconsData.json). It pairs each Segoe Fluent Icons codepoint with a
display name ("Global Nav Button") and carries no categories, so the generated table has
none either: the picker offers name search only.

Each display name becomes a stable lowercase key ("global-nav-button"): runs of anything
that is not [a-z0-9] collapse to one hyphen. The key is what settings store as an icon, so
keys must never change once shipped: when upstream renames a glyph, keep the old key by
adding it to EXTRA_KEYS below rather than letting it drop out.

Usage (from the repo root, no arguments):
    python tools/gen-segoe-fluent-glyphs.py
The script fails on a duplicate key or codepoint. Output is LF, sorted by key (the lookup
binary-searches it, and alphabetical is the picker's browse order).
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "windows/src/cascadia/TerminalSettingsEditor/SegoeFluentIconList.h"
OUTPUT = ROOT / "windows/src/inc/AxanSegoeFluentGlyphs.h"

# Retired keys kept resolvable: key -> codepoint. Empty until upstream renames something.
EXTRA_KEYS: dict[str, int] = {}


def key_of(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")
    pairs = re.findall(r'\{\s*L"\\u([0-9A-Fa-f]{4})",\s*L"([^"]*)"\s*\}', text)
    if not pairs:
        print(f"no glyph pairs found in {SOURCE}", file=sys.stderr)
        return 1

    rows = []
    seen_keys: dict[str, str] = {}
    seen_cps: dict[int, str] = {}
    for hexcp, name in pairs:
        cp = int(hexcp, 16)
        key = key_of(name)
        if not key or not key.isascii():
            print(f"unusable name {name!r}", file=sys.stderr)
            return 1
        if key in seen_keys:
            print(f"duplicate key {key!r}: {seen_keys[key]!r} and {name!r}", file=sys.stderr)
            return 1
        if cp in seen_cps:
            print(f"duplicate codepoint U+{cp:04X}: {seen_cps[cp]!r} and {name!r}", file=sys.stderr)
            return 1
        seen_keys[key] = name
        seen_cps[cp] = name
        rows.append((key, cp, name))
    for key, cp in EXTRA_KEYS.items():
        if key not in seen_keys:
            rows.append((key, cp, seen_cps.get(cp, key)))
    rows.sort(key=lambda r: r[0])

    out = []
    out.append("// Copyright (c) Lonely Quasar.")
    out.append("// Licensed under the MIT license.")
    out.append("//")
    out.append("// GENERATED by tools/gen-segoe-fluent-glyphs.py from upstream's")
    out.append("// TerminalSettingsEditor/SegoeFluentIconList.h (Microsoft's WinUI Gallery glyph list).")
    out.append("// Do not edit by hand; rerun the script. Lookups live in AxanGlyphNames.h.")
    out.append("//")
    out.append("// The Segoe Fluent Icons name table (#39): stable key -> codepoint + display name,")
    out.append("// sorted by key. The source has no categories, so there are none here.")
    out.append("")
    out.append("#pragma once")
    out.append("")
    out.append("#include <array>")
    out.append("#include <string_view>")
    out.append("")
    out.append("namespace Axan::SegoeFluentGlyphs")
    out.append("{")
    out.append("    struct Glyph")
    out.append("    {")
    out.append("        std::wstring_view key; // what settings store, e.g. L\"robot\"")
    out.append("        wchar_t codepoint; // U+E700..U+F8FF")
    out.append("        std::wstring_view displayName; // e.g. L\"Robot\"")
    out.append("    };")
    out.append("")
    out.append(f"    inline constexpr std::array<Glyph, {len(rows)}> kGlyphs{{ {{")
    for key, cp, name in rows:
        out.append(f'        {{ L"{key}", 0x{cp:04X}, L"{name}" }},')
    out.append("    } };")
    out.append("}")
    out.append("")
    OUTPUT.write_bytes("\n".join(out).encode("ascii"))
    print(f"wrote {len(rows)} glyphs to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
