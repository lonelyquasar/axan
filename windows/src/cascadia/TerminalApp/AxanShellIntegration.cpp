    ShellFamily DetectShellFamily(std::wstring_view commandline)
    {
        const auto exe = _exeBasenameLower(commandline);
        if (exe == L"pwsh.exe" || exe == L"powershell.exe")
        {
            return ShellFamily::PowerShell;
        }
        if (exe == L"cmd.exe")
        {
            return ShellFamily::Cmd;
        }
        if (exe == L"wsl.exe")
        {
            return ShellFamily::Wsl;
        }
        return ShellFamily::Unknown;
    }

    ShellIntegration ComputeShellIntegration(std::wstring_view commandline, bool enabled)
    {
        ShellIntegration result;
        result.commandline.assign(commandline);
        if (!enabled)
        {
            return result;
        }

        const auto family = DetectShellFamily(commandline);
        const auto familyName = family == ShellFamily::PowerShell ? "powershell" :
                                family == ShellFamily::Cmd        ? "cmd" :
                                family == ShellFamily::Wsl        ? "wsl" :
                                                                    "unknown";
        Axan::Log::Info("AxanShellIntegration", "ComputeShellIntegration: spawn seam", { { "shell", familyName } });
        if (family == ShellFamily::Unknown)
        {
            return result;
        }

        const auto tokens = _argTokensLower(commandline);

        try
        {
            switch (family)
            {
            case ShellFamily::PowerShell:
            {
                // A custom -Command/-File/-EncodedCommand spawn owns its own behavior; don't
                // collide with it.
                if (_powershellHasRunFlag(tokens))
                {
                    return result;
                }
                const auto script = _shellIntegrationDir() / L"pwsh" / L"axan-shell-integration.ps1";
                if (!_materialize(script, _kPwshScript))
                {
                    return result;
                }

                std::wstring cl{ commandline };
                if (!_hasToken(tokens, L"-noexit"))
                {
                    cl += L" -NoExit";
                }
                cl += L" -Command \". '";
                cl += _psSingleQuoteEscape(script.wstring());
                cl += L"'\"";
                result.commandline = std::move(cl);
                result.applied = true;
                return result;
            }

            case ShellFamily::Cmd:
            {
                // A `/c` one-shot has no interactive prompt to hook. (`/k` is fine: it stays
                // interactive, and the env-based %PROMPT% co-exists with it — best effort.)
                if (_hasToken(tokens, L"/c"))
                {
                    return result;
                }
                // %PROMPT% codes: $E=ESC, $P=cwd, $G='>'. Emit OSC 9;9;"<cwd>" ST, then the
                // conventional "<cwd>>" prompt. cmd re-expands $P each prompt, so cwd tracks.
                result.promptEnv = std::wstring{ L"$E]9;9;\"$P\"$E\\$P$G" };
                result.applied = true;
                return result;
            }

            case ShellFamily::Wsl:
            {
                if (_wslHasOneShot(tokens))
                {
                    return result;
                }
                const auto script = _shellIntegrationDir() / L"bash" / L"axan-rcfile.sh";
                if (!_materialize(script, _kBashRcfile))
                {
                    return result;
                }

                std::wstring cl{ commandline };
                cl += L" -- bash --rcfile \"";
                cl += _toWslMntPath(script);
                cl += L"\" -i";
                result.commandline = std::move(cl);
                result.applied = true;
                return result;
            }

            default:
                return result;
            }
        }
        catch (...)
        {
            // ApplicationData unavailable (unpackaged) or any IO failure: fall back to the
            // unmodified spawn. Shell integration is a nicety, never load-bearing for spawn.
            Axan::Log::Warn("AxanShellIntegration", "ComputeShellIntegration: materialize/IO failed; spawning unmodified", { { "shell", familyName } });
            result.commandline.assign(commandline);
            result.applied = false;
            result.promptEnv.reset();
            return result;
        }
    }
